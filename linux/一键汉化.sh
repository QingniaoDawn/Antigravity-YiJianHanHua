#!/usr/bin/env bash
# ============================================================
# Antigravity 一键汉化 · Linux 版（转发入口）
# ------------------------------------------------------------
# 真正的实现放在仓库根目录的「一键汉化.sh」。
# 这里只做转发，目的是避免同一份逻辑存在两处：
# 早先的两个文件逐字节相同，改一处忘另一处就会行为漂移。
#
# 单独把 linux/ 目录拷走是无法运行的，请整个文件夹一起解压。
# ============================================================

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REAL="$HERE/../一键汉化.sh"

if [ ! -f "$REAL" ]; then
  echo "[错误] 找不到仓库根目录的「一键汉化.sh」。"
  echo "  本文件只是转发入口，真正的脚本在上一层目录。"
  echo "  请确认整个文件夹一起解压后重试。"
  if [ -t 0 ]; then read -r -p "按回车键关闭..." _; fi
  exit 1
fi

exec bash "$REAL" "$@"
